fn is_blank(value: &str) -> bool {
    value.trim().is_empty()
}

fn is_lowercase_sha256_hex(value: &str) -> bool {
    value.len() == 64
        && value
            .bytes()
            .all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b))
}

fn bounded_text(value: &str, max_bytes: usize) -> bool {
    !is_blank(value) && value.len() <= max_bytes
}

/// The server-owned manifest envelope. Keys are stored in ascending byte
/// order, so the envelope identifies the *set* of expected batches.
fn manifest_envelope(manifest_digest: &str, keys: &BTreeSet<String>) -> JsonValue {
    json!({
        "schemaVersion": MANAGED_IMPORT_MANIFEST_SCHEMA,
        "manifestDigest": manifest_digest,
        "expectedBatchKeys": keys.iter().collect::<Vec<_>>(),
    })
}

/// Decode a stored managed-DRIVER manifest envelope into its manifest digest
/// and expected batch keys. Anything that is not exactly that envelope fails
/// closed.
fn decode_manifest_envelope(manifest: &JsonValue) -> Option<(&str, BTreeSet<String>)> {
    let object = manifest.as_object()?;
    let manifest_digest = object.get("manifestDigest")?.as_str()?;
    if object.len() != 3
        || object.get("schemaVersion")?.as_str()? != MANAGED_IMPORT_MANIFEST_SCHEMA
        || !is_lowercase_sha256_hex(manifest_digest)
    {
        return None;
    }
    let keys = object.get("expectedBatchKeys")?.as_array()?;
    let set: BTreeSet<String> = keys
        .iter()
        .map(|key| key.as_str().map(str::to_string))
        .collect::<Option<_>>()?;
    (!set.is_empty() && set.len() == keys.len()).then_some((manifest_digest, set))
}

/// Decode a stored managed-DRIVER manifest envelope into its expected batch
/// keys. Anything that is not exactly that envelope fails closed.
pub(crate) fn expected_batch_keys(manifest: &JsonValue) -> Option<BTreeSet<String>> {
    decode_manifest_envelope(manifest).map(|(_, keys)| keys)
}

/// Validate the begin-import request without touching the database, returning
/// the expected batch-key set.
fn validate_begin(input: &BeginMetricImportInput) -> LifecycleResult<BTreeSet<String>> {
    let keys: BTreeSet<String> = input.expected_batch_keys.iter().cloned().collect();
    let valid = bounded_text(&input.upstream_report_id, MAX_UPSTREAM_REPORT_ID_BYTES)
        && input.period_start.succ_opt() == Some(input.period_end)
        && bounded_text(&input.format_code, MAX_FORMAT_FIELD_BYTES)
        && bounded_text(&input.format_version, MAX_FORMAT_FIELD_BYTES)
        && bounded_text(&input.normalizer_version, MAX_FORMAT_FIELD_BYTES)
        && input
            .raw_sha256
            .as_deref()
            .is_none_or(is_lowercase_sha256_hex)
        && is_lowercase_sha256_hex(&input.manifest_digest)
        && !keys.is_empty()
        && keys.len() <= MAX_EXPECTED_BATCH_KEYS
        && keys.len() == input.expected_batch_keys.len()
        && keys
            .iter()
            .all(|key| bounded_text(key, MAX_BATCH_KEY_BYTES));
    if valid {
        Ok(keys)
    } else {
        Err(MetricLifecycleError::LifecycleLimitExceeded)
    }
}

/// Parse a canonical base-10 signed 64-bit integer: no sign other than a
/// leading `-`, no leading zero, no `-0`, no whitespace, no exponent.
fn parse_canonical_i64(value: &str) -> Option<i64> {
    let parsed: i64 = value.parse().ok()?;
    (parsed.to_string() == value).then_some(parsed)
}

/// Map the transport batch onto the coordinator's request, converting only the
/// two representation-level fields and interpreting nothing else.
fn to_coordinator_batch(input: &IngestMetricBatchInput) -> LifecycleResult<MetricIngestionBatch> {
    let observations = input
        .observations
        .iter()
        .map(|observation| {
            let value = parse_canonical_i64(&observation.value)
                .ok_or(MetricLifecycleError::LifecycleLimitExceeded)?;
            let source_row_number = observation
                .source_row_number
                .map(|number| {
                    if number < 0 {
                        Err(MetricLifecycleError::LifecycleLimitExceeded)
                    } else {
                        Ok(i64::from(number))
                    }
                })
                .transpose()?;
            Ok(NormalizedMetricObservation {
                source_account_code: observation.source_account_code.clone(),
                platform_code: observation.platform_code.clone(),
                measure_code: observation.measure_code.clone(),
                work_doi: observation.work_doi.clone(),
                publication_isbn: observation.publication_isbn.clone(),
                publication_type: observation.publication_type,
                period_start: observation.period_start,
                period_end: observation.period_end,
                reporting_grain: observation.reporting_grain,
                country_code: observation.country_code.clone(),
                institution_ror: observation.institution_ror.clone(),
                value,
                source_record_id: observation.source_record_id.clone(),
                methodology_version: observation.methodology_version.clone(),
                source_row_number,
            })
        })
        .collect::<LifecycleResult<Vec<_>>>()?;
    let coverage = input
        .coverage
        .iter()
        .map(|assertion| NormalizedMetricCoverageAssertion {
            platform_code: assertion.platform_code.clone(),
            measure_code: assertion.measure_code.clone(),
            period_start: assertion.period_start,
            period_end: assertion.period_end,
            status: assertion.status,
            country_coverage: assertion.country_coverage,
            institution_coverage: assertion.institution_coverage,
            notes: assertion.notes.clone(),
        })
        .collect();
    Ok(MetricIngestionBatch {
        import_id: input.import_id,
        batch_key: input.batch_key.clone(),
        schema_version: input.schema_version.clone(),
        observations,
        coverage,
    })
}

/// What an eligible managed-DRIVER route resolves to.
struct EligibleRoute {
    /// The account's pinned publisher.
    publisher_id: Uuid,
    /// Stable code of the enabled platform row eligibility was decided from.
    platform_code: String,
}

/// Whether one source account is an eligible managed-DRIVER route for its
/// source, returning its pinned publisher and the stable code of the platform
/// row eligibility was decided from.
///
/// `lock` reads the platform and publisher `FOR SHARE`, the order the
/// canonical coordinator uses. The claim's candidate enumeration reads them
/// without locks; the claim then revalidates every locked checkpoint's unit
/// under locks before it grants a lease, and every later operation revalidates
/// under locks again.
fn check_eligibility(
    connection: &mut PgConnection,
    source: &MetricSource,
    account: &MetricSourceAccount,
    lock: bool,
) -> LifecycleResult<EligibleRoute> {
    use MetricLifecycleError::{MetricsCollectNotEntitled, SourceNotEligible};
    if source.acquisition_type != MetricSourceAcquisitionType::Driver
        || !source.enabled
        || !account.enabled
        || account.source_id != source.source_id
    {
        return Err(SourceNotEligible);
    }
    let platform_query = metric_platform::table.find(account.platform_id);
    let platform: Option<MetricPlatform> = if lock {
        platform_query.for_share().first(connection).optional()?
    } else {
        platform_query.first(connection).optional()?
    };
    let platform = platform
        .filter(|platform| platform.enabled)
        .ok_or(SourceNotEligible)?;
    let publisher_id = account.expected_publisher_id.ok_or(SourceNotEligible)?;
    let package_query = publisher::table
        .find(publisher_id)
        .select(publisher::subscription_package);
    let package: Option<ThothPackage> = if lock {
        package_query.for_share().first(connection).optional()?
    } else {
        package_query.first(connection).optional()?
    };
    let package = package.ok_or(SourceNotEligible)?;
    let configuration = account
        .decoded_configuration()
        .map_err(|_| SourceNotEligible)?;
    check_source_compatibility(source, configuration.kind).map_err(|_| SourceNotEligible)?;
    if !package.has_capability(PublisherCapability::MetricsCollect) {
        return Err(MetricsCollectNotEntitled);
    }
    Ok(EligibleRoute {
        publisher_id,
        platform_code: platform.code,
    })
}

/// The account's `default` checkpoint, locked `FOR UPDATE`, with its lease
/// liveness decided against the transaction timestamp.
#[derive(diesel::QueryableByName)]
struct LockedCheckpoint {
    #[diesel(sql_type = SqlUuid)]
    source_checkpoint_id: Uuid,
    #[diesel(sql_type = Nullable<Text>)]
    lease_owner: Option<String>,
    #[diesel(sql_type = Bool)]
    lease_is_live: bool,
}

fn lock_checkpoint(
    connection: &mut PgConnection,
    source_account_id: Uuid,
) -> LifecycleResult<Option<LockedCheckpoint>> {
    Ok(sql_query(
        "SELECT source_checkpoint_id, lease_owner, \
                (lease_expires_at IS NOT NULL \
                 AND lease_expires_at > transaction_timestamp()) AS lease_is_live \
           FROM metric_source_checkpoint \
          WHERE source_account_id = $1 AND partition_key = $2 \
          FOR UPDATE",
    )
    .bind::<SqlUuid, _>(source_account_id)
    .bind::<Text, _>(DEFAULT_PARTITION_KEY)
    .get_result(connection)
    .optional()?)
}

/// Whether the locked checkpoint is held by exactly this live token.
fn holds_live_claim(checkpoint: &LockedCheckpoint, lease_token: Uuid) -> bool {
    checkpoint.lease_is_live
        && checkpoint.lease_owner.as_deref() == Some(lease_token.to_string().as_str())
}

/// Lock the account's checkpoint and require the caller's live claim.
fn require_live_claim(
    connection: &mut PgConnection,
    source_account_id: Uuid,
    lease_token: Uuid,
) -> LifecycleResult<Uuid> {
    match lock_checkpoint(connection, source_account_id)? {
        Some(checkpoint) if holds_live_claim(&checkpoint, lease_token) => {
            Ok(checkpoint.source_checkpoint_id)
        }
        _ => Err(MetricLifecycleError::StaleSourceClaim),
    }
}

fn find_import(connection: &mut PgConnection, import_id: Uuid) -> LifecycleResult<MetricImport> {
    metric_import::table
        .find(import_id)
        .first(connection)
        .optional()?
        .ok_or(MetricLifecycleError::ImportNotFound)
}

