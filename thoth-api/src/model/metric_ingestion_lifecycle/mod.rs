//! Managed-DRIVER Metrics ingestion lifecycle (`MET-WP2-02`).
//!
//! This module owns the repository-internal protocol behind the five protected
//! `METRICS_INGEST_SERVICE` lifecycle operations. It is transport and lifecycle
//! only: canonical ingestion is delegated unchanged to
//! [`ingest_metric_batch`](crate::model::metric_ingestion::ingest_metric_batch),
//! and the only durable state touched here is the existing
//! `metric_source_checkpoint` lease, progress and cursor row, the existing
//! `metric_import` envelope and, read-only, the committed `metric_import_batch`
//! and `metric_coverage` evidence. There is no second queue, no process-local
//! claim ledger and no generic worker or job abstraction.
//!
//! # One source unit
//!
//! For MOM-1 a source unit is one source account's single `default` checkpoint
//! partition. The lifecycle of one collected day is:
//!
//! ```text
//! claim_metric_source_units       lazily create, then lease (source_account_id, "default")
//!   -> begin_metric_import        create or recover the one import for the upstream report
//!   -> ingest_metric_batch_under_claim   every expected batch, through the #900 coordinator
//!   -> complete_metric_import     close the import from its committed batches
//!   -> update_metric_source_checkpoint   record progress and release the lease
//! ```
//!
//! # Claim token
//!
//! `metric_source_checkpoint.lease_owner` holds the canonical lowercase text of
//! an opaque UUID generated by Thoth for every successful claim or reclaim. It
//! is returned only in the fresh claim, is never a principal identity, and is
//! required by every later operation. A caller holds a *live* claim only while
//! the stored token equals its token and `lease_expires_at` is after the
//! transaction timestamp, both checked under the checkpoint row lock.
//!
//! # Claim context and period-manifest cursor (`MET-WP2-03`)
//!
//! A claim carries the source and account rows it revalidated under its locks,
//! the stable `platform_code` copied from the platform row it locked
//! `FOR SHARE` and found enabled, and the checkpoint's accepted
//! [`MetricPeriodManifestCursor`], decoded while that checkpoint is locked and
//! before its lease is written. A stored cursor outside the closed
//! representation fails the whole claim as `INTERNAL_STATE_INCONSISTENCY`, so
//! no lease is granted over it.
//!
//! No caller ever supplies cursor state. `update_metric_source_checkpoint`
//! derives the one entry it may record from the terminal import's own
//! `period_start` and the `manifestDigest` of its strict managed envelope, and
//! records it only under the same successful-period predicate that advances
//! `last_successful_period_end`, or under the one narrow CloudFront
//! quarantine-only exception below, in the one `UPDATE` that also records
//! progress and releases the claim.
//!
//! # CloudFront quarantine-only manifest acceptance (`MET-WP7-PREREQ-02`)
//!
//! A `COMPLETED_WITH_ERRORS` import is never canonically successful and never
//! advances `last_successful_period_end`. Only when the locked source's
//! `driver_key` is exactly `cloudfront` does the update derive, from the
//! import's own durable `metric_record_provenance` and
//! `metric_identifier_quarantine` rows, how many rows were rejected, how many
//! of those were `UNKNOWN_DOI`, how many quarantine rows the import has and
//! how many of those belong to `UNKNOWN_DOI` rejections. Provenance is the
//! classification authority; `metric_import_error` is never consulted.
//!
//! - **Inconsistent**: the rejected count differs from `invalid_count`, a
//!   quarantine row belongs to any other provenance, or a rejected row's
//!   `details.reason_code` is absent, null, not a string or outside the closed
//!   vocabulary. The update fails as `INTERNAL_STATE_INCONSISTENCY` and writes
//!   no progress, cursor, successful period or release.
//! - **Consistent but ineligible**: any conflict, any rejection other than
//!   `UNKNOWN_DOI`, or any `UNKNOWN_DOI` rejection without quarantine (which is
//!   how an observation the coordinator deliberately did not quarantine
//!   looks). The ordinary non-success path applies: progress and release, no
//!   cursor, no successful period.
//! - **Quarantine-only**: nothing conflicted, every invalid row is a
//!   quarantined `UNKNOWN_DOI` rejection and coverage is exactly `COMPLETE`
//!   for the one-day period. The update records `last_completed_at`, records
//!   or replaces the period's manifest digest under the unchanged cursor
//!   rules, and releases the claim, but still never advances
//!   `last_successful_period_end`.
//!
//! The whole predicate is derived before the live/released split, so a
//! released replay stays read-only and recognizes recorded completion from
//! `last_completed_at` alone; the cursor is never a replay authority. Other
//! sources never evaluate quarantine evidence.
//!
//! # Transactions and lock order
//!
//! Every operation except the batch runs in one transaction that, after the
//! caller's authorization, locks the account's `default` checkpoint row
//! `FOR UPDATE` before reading or writing anything else it depends on. Source
//! authority rows are then read `FOR SHARE` in the canonical coordinator's own
//! order (account, source, platform, publisher). Because every lease-sensitive
//! operation on one account queues on that one row first, begin, batch,
//! completion and checkpoint progress for one account are serialized. The
//! checkpoint update's order is fixed as checkpoint `FOR UPDATE`, import
//! `FOR SHARE`, source account `FOR SHARE`, then source `FOR SHARE`.
//!
//! The claim follows the same order with one difference: it takes its
//! checkpoint rows `FOR UPDATE SKIP LOCKED`, so it never waits on a checkpoint.
//! It enumerates candidate accounts with plain reads, ensures and locks their
//! checkpoints, and only then, per locked checkpoint, locks the account,
//! source, platform and publisher rows `FOR SHARE` and decides eligibility from
//! those locked rows (CR-1, #908). `FOR SHARE` is the weakest row lock that
//! conflicts with every canonical writer of that authority: the #904 source and
//! source-account coordinators and the platform coordinator lock their one row
//! `FOR UPDATE`, and the BE-01 service-configuration coordinator, the only
//! writer of `publisher.subscription_package`, locks the publisher row
//! `FOR UPDATE` first. A writer that committed before the claim's lock is seen
//! by the locked reload, and the unit is skipped or the claim fails closed; a
//! writer that arrives after it waits until the claim has committed. The
//! shares are compatible with the shares begin and the coordinator take on the
//! same rows, and each writer above holds exactly one authority row and waits
//! on nothing the lifecycle holds, so no lock cycle is introduced.
//!
//! The batch uses the bounded two-connection guard fixed by Specification
//! Amendment 2: a short guard transaction locks and validates the checkpoint
//! row, checks the batch key, and **while holding that lock** calls the
//! unchanged coordinator, which uses its own pooled connection and transaction.
//! A concurrent reclaim uses `FOR UPDATE SKIP LOCKED` on the same row, so it
//! cannot replace the token while the coordinator runs. Nothing outside the
//! local coordinator call happens inside the guard.

