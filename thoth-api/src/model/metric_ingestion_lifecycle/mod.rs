impl TryFrom<MetricIngestionOutcome> for MetricBatchResult {
    type Error = MetricLifecycleError;

    fn try_from(outcome: MetricIngestionOutcome) -> LifecycleResult<Self> {
        let rows = outcome
            .rows
            .into_iter()
            .map(|row| {
                Ok(MetricIngestionRowResult {
                    batch_row_index: i32::try_from(row.batch_row_index)
                        .map_err(|_| MetricIngestionErrorCode::InternalStateInconsistency)?,
                    classification: row.classification,
                    reason_code: row.reason_code,
                    record_id: row.record_id,
                    identity_hash: row.identity_hash,
                    content_hash: row.content_hash,
                })
            })
            .collect::<LifecycleResult<Vec<_>>>()?;
        Ok(MetricBatchResult {
            import_batch_id: outcome.import_batch_id,
            request_hash: outcome.request_hash,
            replayed: outcome.replayed,
            rows,
        })
    }
}

