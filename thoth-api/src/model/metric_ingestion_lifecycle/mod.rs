/// A lifecycle failure: one of the closed lifecycle classifications frozen by
/// Specification Amendment 3, or an authoritative coordinator code carried
/// through without rewriting.
///
/// Every failure rolls back its transaction, so a failed call leaves durable
/// state exactly as it was. No variant carries SQL, a constraint name, a
/// connection detail, a token, configuration or caller input.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum MetricLifecycleError {
    /// No source carries the requested stable code.
    SourceNotFound,
    /// No source account carries the requested stable code.
    SourceAccountNotFound,
    /// The source or account is not an enabled, correctly configured managed
    /// `DRIVER` route with an enabled platform and a pinned publisher.
    SourceNotEligible,
    /// The account's pinned publisher lacks the `METRICS_COLLECT` capability.
    MetricsCollectNotEntitled,
    /// The caller does not hold the live claim: the token is unknown, foreign,
    /// expired, reclaimed or already released.
    StaleSourceClaim,
    /// No import carries the requested identifier.
    ImportNotFound,
    /// An import already exists for the upstream report with different
    /// immutable values.
    ImportIdempotencyMismatch,
    /// The batch key is not one the import declared.
    UnexpectedBatchKey,
    /// Not every expected batch has been committed.
    ImportIncomplete,
    /// The import is not a managed-DRIVER import in a state the operation
    /// accepts.
    InvalidImportState,
    /// A lifecycle input is outside its approved bounds or format.
    LifecycleLimitExceeded,
    /// A failure owned by the canonical ingestion coordinator vocabulary.
    Ingestion(MetricIngestionErrorCode),
}

impl MetricLifecycleError {
    /// The stable machine-readable code, returned as `extensions.type`.
    pub fn code(self) -> String {
        use MetricLifecycleError::*;
        match self {
            SourceNotFound => "SOURCE_NOT_FOUND".to_string(),
            SourceAccountNotFound => "SOURCE_ACCOUNT_NOT_FOUND".to_string(),
            SourceNotEligible => "SOURCE_NOT_ELIGIBLE".to_string(),
            MetricsCollectNotEntitled => "METRICS_COLLECT_NOT_ENTITLED".to_string(),
            StaleSourceClaim => "STALE_SOURCE_CLAIM".to_string(),
            ImportNotFound => "IMPORT_NOT_FOUND".to_string(),
            ImportIdempotencyMismatch => "IMPORT_IDEMPOTENCY_MISMATCH".to_string(),
            UnexpectedBatchKey => "UNEXPECTED_BATCH_KEY".to_string(),
            ImportIncomplete => "IMPORT_INCOMPLETE".to_string(),
            InvalidImportState => "INVALID_IMPORT_STATE".to_string(),
            LifecycleLimitExceeded => "LIFECYCLE_LIMIT_EXCEEDED".to_string(),
            Ingestion(code) => code.to_string(),
        }
    }

    /// The fixed client-facing message. Never derived from input or state.
    pub fn message(self) -> &'static str {
        use MetricLifecycleError::*;
        match self {
            SourceNotFound => "The metric source was not found.",
            SourceAccountNotFound => "The metric source account was not found.",
            SourceNotEligible => "The metric source is not eligible for managed collection.",
            MetricsCollectNotEntitled => {
                "The publisher is not entitled to managed metrics collection."
            }
            StaleSourceClaim => "The source claim is not held by this lease token.",
            ImportNotFound => "The metric import was not found.",
            ImportIdempotencyMismatch => {
                "A metric import already exists for this upstream report with different values."
            }
            UnexpectedBatchKey => "The batch key is not one the metric import expects.",
            ImportIncomplete => "Not every expected batch of the metric import has been ingested.",
            InvalidImportState => "The metric import is not in a state this operation accepts.",
            LifecycleLimitExceeded => "A lifecycle input is outside its permitted bounds.",
            Ingestion(_) => "The metric ingestion request was refused.",
        }
    }
}

impl std::fmt::Display for MetricLifecycleError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{}", self.code())
    }
}

impl std::error::Error for MetricLifecycleError {}

impl From<MetricIngestionErrorCode> for MetricLifecycleError {
    fn from(code: MetricIngestionErrorCode) -> Self {
        MetricLifecycleError::Ingestion(code)
    }
}

impl From<DieselError> for MetricLifecycleError {
    fn from(error: DieselError) -> Self {
        log::error!("metric ingestion lifecycle database failure: {error}");
        MetricLifecycleError::Ingestion(MetricIngestionErrorCode::InternalDatabaseError)
    }
}

impl From<PoolError> for MetricLifecycleError {
    fn from(error: PoolError) -> Self {
        log::error!("metric ingestion lifecycle could not obtain a database connection: {error}");
        MetricLifecycleError::Ingestion(MetricIngestionErrorCode::InternalDatabaseError)
    }
}

impl IntoFieldError for MetricLifecycleError {
    fn into_field_error(self) -> FieldError {
        let mut extensions = juniper::Object::with_capacity(1);
        extensions.add_field("type", juniper::Value::scalar(self.code()));
        FieldError::new(self.message(), juniper::Value::Object(extensions))
    }
}

type LifecycleResult<T> = Result<T, MetricLifecycleError>;

