/// One checkpoint the claim has locked `FOR UPDATE SKIP LOCKED`.
#[derive(diesel::QueryableByName)]
struct SelectedCheckpoint {
    #[diesel(sql_type = SqlUuid)]
    source_checkpoint_id: Uuid,
    #[diesel(sql_type = SqlUuid)]
    source_account_id: Uuid,
}

/// The locked canonical authority one claimed unit is leased from.
struct ClaimAuthority {
    source: MetricSource,
    account: MetricSourceAccount,
    /// Stable code of the platform row locked `FOR SHARE` and found enabled.
    platform_code: String,
}

/// Reload and lock `FOR SHARE`, in the lifecycle's lock order, every mutable
/// canonical authority row behind one locked checkpoint, and decide the unit's
/// eligibility from those rows alone.
///
/// This is the CR-1 claim-time revalidation: the rows it returns, and the
/// platform code it copies from the platform row it locked, are the authority
/// the lease is granted from, and their shares are held until the claim
/// commits, so no canonical writer can commit a conflicting change in between.
/// A source that is no longer an enabled `DRIVER` source fails the whole claim
/// closed, exactly as it does before enumeration. A unit whose account,
/// platform, publisher pin, configuration or entitlement is no longer eligible
/// is skipped: `None` grants nothing and leaves the checkpoint unleased.
fn revalidate_claim_authority(
    connection: &mut PgConnection,
    source_id: Uuid,
    source_account_id: Uuid,
) -> LifecycleResult<Option<ClaimAuthority>> {
    let account: Option<MetricSourceAccount> = metric_source_account::table
        .find(source_account_id)
        .for_share()
        .first(connection)
        .optional()?;
    let Some(account) = account else {
        return Ok(None);
    };
    let source: MetricSource = metric_source::table
        .find(source_id)
        .for_share()
        .first(connection)?;
    if source.acquisition_type != MetricSourceAcquisitionType::Driver || !source.enabled {
        return Err(MetricLifecycleError::SourceNotEligible);
    }
    match check_eligibility(connection, &source, &account, true) {
        Ok(route) => Ok(Some(ClaimAuthority {
            source,
            account,
            platform_code: route.platform_code,
        })),
        Err(
            MetricLifecycleError::SourceNotEligible
            | MetricLifecycleError::MetricsCollectNotEntitled,
        ) => Ok(None),
        Err(error) => Err(error),
    }
}

/// Decode the stored cursor of a checkpoint this transaction holds locked.
///
/// A value outside the closed representation is internal state inconsistency:
/// it is never read as empty and never repaired, and the failure carries none
/// of the stored value.
fn locked_period_manifest_cursor(
    connection: &mut PgConnection,
    source_checkpoint_id: Uuid,
) -> LifecycleResult<Option<MetricPeriodManifestCursor>> {
    let stored: Option<JsonValue> = metric_source_checkpoint::table
        .find(source_checkpoint_id)
        .select(metric_source_checkpoint::cursor)
        .first(connection)?;
    MetricPeriodManifestCursor::decode(stored.as_ref()).map_err(|_| {
        log::error!(
            "metric source checkpoint {source_checkpoint_id} holds an unsupported period-manifest cursor"
        );
        MetricIngestionErrorCode::InternalStateInconsistency.into()
    })
}

/// Claim up to `limit` units of one managed-DRIVER source.
///
/// One transaction: resolve the source, select the eligible enabled accounts in
/// ascending stable-code order, ensure each has its `default` checkpoint with a
/// conflict-safe insert, lock the unleased or expired checkpoints
/// `FOR UPDATE SKIP LOCKED` in the same order, then, for each locked
/// checkpoint, lock and revalidate its account, source, platform and publisher
/// `FOR SHARE`, decode its stored period-manifest cursor, and lease it under a
/// fresh token from that locked state only. A row another claimer holds locked
/// is skipped, never waited on. An account that is ineligible at enumeration is
/// skipped and gains no checkpoint; one that became ineligible by revalidation
/// is skipped, its cursor unread and its checkpoint unleased; a source that
/// became ineligible, or an eligible unit whose stored cursor is outside the
/// closed representation, fails the claim closed.
pub fn claim_metric_source_units(
    db: &PgPool,
    input: &ClaimMetricSourceUnitsInput,
) -> LifecycleResult<Vec<MetricSourceUnitClaim>> {
    let limit = input.limit.unwrap_or(CLAIM_DEFAULT_LIMIT);
    if limit <= 0 {
        return Ok(Vec::new());
    }
    let limit = limit.min(CLAIM_MAX_LIMIT);
    let lease_seconds = input
        .lease_seconds
        .unwrap_or(LEASE_DEFAULT_SECONDS)
        .clamp(LEASE_MIN_SECONDS, LEASE_MAX_SECONDS);

    let mut connection = db.get()?;
    connection.transaction(|connection| {
        let source: MetricSource = metric_source::table
            .filter(metric_source::code.eq(&input.source_code))
            .first(connection)
            .optional()?
            .ok_or(MetricLifecycleError::SourceNotFound)?;
        if source.acquisition_type != MetricSourceAcquisitionType::Driver || !source.enabled {
            return Err(MetricLifecycleError::SourceNotEligible);
        }

        let accounts: Vec<MetricSourceAccount> = metric_source_account::table
            .filter(metric_source_account::source_id.eq(source.source_id))
            .filter(metric_source_account::enabled.eq(true))
            .order(metric_source_account::code.asc())
            .load(connection)?;
        let mut eligible = Vec::with_capacity(accounts.len());
        for account in accounts {
            match check_eligibility(connection, &source, &account, false) {
                Ok(_) => eligible.push(account),
                Err(
                    MetricLifecycleError::SourceNotEligible
                    | MetricLifecycleError::MetricsCollectNotEntitled,
                ) => {}
                Err(error) => return Err(error),
            }
        }
        if eligible.is_empty() {
            return Ok(Vec::new());
        }

        for account in &eligible {
            diesel::insert_into(metric_source_checkpoint::table)
                .values((
                    metric_source_checkpoint::source_account_id.eq(account.source_account_id),
                    metric_source_checkpoint::partition_key.eq(DEFAULT_PARTITION_KEY),
                ))
                .on_conflict((
                    metric_source_checkpoint::source_account_id,
                    metric_source_checkpoint::partition_key,
                ))
                .do_nothing()
                .execute(connection)?;
        }

        let account_ids: Vec<Uuid> = eligible.iter().map(|a| a.source_account_id).collect();
        let selected: Vec<SelectedCheckpoint> = sql_query(
            "SELECT c.source_checkpoint_id, c.source_account_id \
               FROM metric_source_checkpoint c \
               JOIN metric_source_account a ON a.source_account_id = c.source_account_id \
              WHERE c.source_account_id = ANY($1) \
                AND c.partition_key = $2 \
                AND (c.lease_expires_at IS NULL \
                     OR c.lease_expires_at <= transaction_timestamp()) \
              ORDER BY a.code \
              LIMIT $3 \
              FOR UPDATE OF c SKIP LOCKED",
        )
        .bind::<Array<SqlUuid>, _>(&account_ids)
        .bind::<Text, _>(DEFAULT_PARTITION_KEY)
        .bind::<BigInt, _>(i64::from(limit))
        .load(connection)?;

        let mut claims = Vec::with_capacity(selected.len());
        for row in selected {
            let Some(authority) =
                revalidate_claim_authority(connection, source.source_id, row.source_account_id)?
            else {
                continue;
            };
            let period_manifest_cursor =
                locked_period_manifest_cursor(connection, row.source_checkpoint_id)?;
            let lease_token = Uuid::new_v4();
            sql_query(
                "UPDATE metric_source_checkpoint \
                    SET lease_owner = $1, \
                        lease_expires_at = transaction_timestamp() + ($2 * interval '1 second') \
                  WHERE source_checkpoint_id = $3",
            )
            .bind::<Text, _>(lease_token.to_string())
            .bind::<Integer, _>(lease_seconds)
            .bind::<SqlUuid, _>(row.source_checkpoint_id)
            .execute(connection)?;
            let checkpoint: MetricSourceCheckpoint = metric_source_checkpoint::table
                .find(row.source_checkpoint_id)
                .first(connection)?;
            let lease_expires_at = checkpoint
                .lease_expires_at
                .ok_or(MetricIngestionErrorCode::InternalStateInconsistency)?;
            claims.push(MetricSourceUnitClaim {
                source: authority.source,
                source_account: authority.account,
                platform_code: authority.platform_code,
                checkpoint,
                period_manifest_cursor,
                lease_token,
                lease_expires_at,
            });
        }
        Ok(claims)
    })
}

/// Create, or recover, the one managed-DRIVER import for an upstream report of
/// a claimed account.
///
/// Authority is never taken from the caller: the account comes from its exact
/// code and the live claim, and the publisher from the account's pin. A new
/// import is `PROCESSING` and records discovery on the checkpoint. An existing
/// import for the same `(source_account_id, upstream_report_id)` is returned
/// unchanged, in whatever state it is, only when every immutable value and the
/// manifest envelope match; otherwise nothing changes.
pub fn begin_metric_import(
    db: &PgPool,
    actor: &str,
    input: &BeginMetricImportInput,
) -> LifecycleResult<MetricImport> {
    let keys = validate_begin(input)?;
    let manifest = manifest_envelope(&input.manifest_digest, &keys);

    let mut connection = db.get()?;
    connection.transaction(|connection| {
        let source_account_id: Uuid = metric_source_account::table
            .filter(metric_source_account::code.eq(&input.source_account_code))
            .select(metric_source_account::source_account_id)
            .first(connection)
            .optional()?
            .ok_or(MetricLifecycleError::SourceAccountNotFound)?;
        let checkpoint_id = require_live_claim(connection, source_account_id, input.lease_token)?;

        let account: MetricSourceAccount = metric_source_account::table
            .find(source_account_id)
            .for_share()
            .first(connection)?;
        let source: MetricSource = metric_source::table
            .find(account.source_id)
            .for_share()
            .first(connection)?;
        let publisher_id = check_eligibility(connection, &source, &account, true)?.publisher_id;

        let existing: Option<MetricImport> = metric_import::table
            .filter(metric_import::source_account_id.eq(source_account_id))
            .filter(metric_import::upstream_report_id.eq(&input.upstream_report_id))
            .first(connection)
            .optional()?;
        if let Some(existing) = existing {
            let compatible = existing.publisher_id == Some(publisher_id)
                && existing.format_code == input.format_code
                && existing.format_version == input.format_version
                && existing.normalizer_version == input.normalizer_version
                && existing.raw_object_key.is_none()
                && existing.raw_sha256 == input.raw_sha256
                && existing.period_start == Some(input.period_start)
                && existing.period_end == Some(input.period_end)
                && existing.manifest == manifest;
            return if compatible {
                Ok(existing)
            } else {
                Err(MetricLifecycleError::ImportIdempotencyMismatch)
            };
        }

        let import: MetricImport = diesel::insert_into(metric_import::table)
            .values((
                metric_import::source_account_id.eq(source_account_id),
                metric_import::publisher_id.eq(publisher_id),
                metric_import::format_code.eq(&input.format_code),
                metric_import::format_version.eq(&input.format_version),
                metric_import::raw_object_key.eq(None::<String>),
                metric_import::raw_sha256.eq(input.raw_sha256.as_deref()),
                metric_import::upstream_report_id.eq(&input.upstream_report_id),
                metric_import::period_start.eq(input.period_start),
                metric_import::period_end.eq(input.period_end),
                metric_import::status.eq(MetricImportStatus::Processing),
                metric_import::normalizer_version.eq(&input.normalizer_version),
                metric_import::manifest.eq(&manifest),
                metric_import::created_by.eq(actor),
            ))
            .get_result(connection)?;
        sql_query(
            "UPDATE metric_source_checkpoint \
                SET last_discovered_at = transaction_timestamp() \
              WHERE source_checkpoint_id = $1",
        )
        .bind::<SqlUuid, _>(checkpoint_id)
        .execute(connection)?;
        Ok(import)
    })
}

/// Ingest one expected batch of a claimed import through the canonical
/// coordinator, under the two-connection lease guard.
///
/// The guard transaction locks and validates the checkpoint and the batch key,
/// then — still holding that lock — calls the unchanged coordinator on its own
/// pooled connection. The coordinator's result, success or failure, is
/// returned as it is; a coordinator failure is carried by its authoritative
/// code. A replay of a committed batch returns the persisted outcome.
pub fn ingest_metric_batch_under_claim(
    db: &PgPool,
    input: &IngestMetricBatchInput,
) -> LifecycleResult<MetricBatchResult> {
    let batch = to_coordinator_batch(input)?;

    let mut guard = db.get()?;
    guard.transaction(|connection| {
        let import = find_import(connection, input.import_id)?;
        require_live_claim(connection, import.source_account_id, input.lease_token)?;
        let expected = expected_batch_keys(&import.manifest)
            .ok_or(MetricLifecycleError::InvalidImportState)?;
        if !expected.contains(&input.batch_key) {
            return Err(MetricLifecycleError::UnexpectedBatchKey);
        }
        let outcome = ingest_metric_batch(db, &batch)
            .map_err(|error| MetricLifecycleError::Ingestion(error.code))?;
        MetricBatchResult::try_from(outcome)
    })
}

/// Close a claimed import from its committed batches.
///
/// Requires every expected batch key, and no other, to be committed. The
/// terminal status is derived from the coordinator's persisted counters, never
/// from the caller: `COMPLETED` when nothing was invalid or conflicting,
/// otherwise `COMPLETED_WITH_ERRORS`. An already terminal import is returned
/// unchanged.
pub fn complete_metric_import(
    db: &PgPool,
    input: &CompleteMetricImportInput,
) -> LifecycleResult<MetricImport> {
    let mut connection = db.get()?;
    connection.transaction(|connection| {
        let import = find_import(connection, input.import_id)?;
        require_live_claim(connection, import.source_account_id, input.lease_token)?;
        let import: MetricImport = metric_import::table
            .find(input.import_id)
            .for_update()
            .first(connection)?;
        let expected = expected_batch_keys(&import.manifest)
            .ok_or(MetricLifecycleError::InvalidImportState)?;
        match import.status {
            MetricImportStatus::Completed | MetricImportStatus::CompletedWithErrors => {
                return Ok(import)
            }
            MetricImportStatus::Processing => {}
            _ => return Err(MetricLifecycleError::InvalidImportState),
        }

        let committed: BTreeSet<String> = metric_import_batch::table
            .filter(metric_import_batch::import_id.eq(import.import_id))
            .select(metric_import_batch::batch_key)
            .load::<String>(connection)?
            .into_iter()
            .collect();
        if !committed.is_subset(&expected) {
            return Err(MetricLifecycleError::InvalidImportState);
        }
        if committed != expected {
            return Err(MetricLifecycleError::ImportIncomplete);
        }

        let status = if import.invalid_count == 0 && import.conflict_count == 0 {
            MetricImportStatus::Completed
        } else {
            MetricImportStatus::CompletedWithErrors
        };
        Ok(diesel::update(metric_import::table.find(import.import_id))
            .set((
                metric_import::status.eq(status),
                metric_import::completed_at.eq(diesel::dsl::sql::<Nullable<Timestamptz>>(
                    "transaction_timestamp()",
                )),
            ))
            .get_result(connection)?)
    })
}

