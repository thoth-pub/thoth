//! Managed-DRIVER Metrics ingestion lifecycle (`MET-WP2-02`).
//!
//! This module owns the repository-internal protocol behind the five protected
//! `METRICS_INGEST_SERVICE` lifecycle operations. It is transport and lifecycle
//! only: canonical ingestion is delegated unchanged to
//! [`ingest_metric_batch`](crate::model::metric_ingestion::ingest_metric_batch),
//! and the only durable state touched here is the existing
//! `metric_source_checkpoint` lease/progress row, the existing `metric_import`
//! envelope and, read-only, the committed `metric_import_batch` and
//! `metric_coverage` evidence. There is no second queue, no process-local claim
//! ledger and no generic worker or job abstraction.
//!
//! # One source unit
//!
//! For MOM-1 a source unit is one source account's single `default` checkpoint
//! partition. The lifecycle of one collected day is:
//!
//! ```text
//! claim_metric_source_units       lazily create, then lease (source_account_id, "default")
//!   -> begin_metric_import        create or recover the one import for the upstream report
//!   -> ingest_metric_batch_under_claim   every expected batch, through the #900 coordinator
//!   -> complete_metric_import     close the import from its committed batches
//!   -> update_metric_source_checkpoint   record progress and release the lease
//! ```
//!
//! # Claim token
//!
//! `metric_source_checkpoint.lease_owner` holds the canonical lowercase text of
//! an opaque UUID generated by Thoth for every successful claim or reclaim. It
//! is returned only in the fresh claim, is never a principal identity, and is
//! required by every later operation. A caller holds a *live* claim only while
//! the stored token equals its token and `lease_expires_at` is after the
//! transaction timestamp, both checked under the checkpoint row lock.
//!
//! # Transactions and lock order
//!
//! Every operation except the batch runs in one transaction that, after the
//! caller's authorization, locks the account's `default` checkpoint row
//! `FOR UPDATE` before reading or writing anything else it depends on. Source
//! authority rows are then read `FOR SHARE` in the canonical coordinator's own
//! order (account, source, platform, publisher). Because every lease-sensitive
//! operation on one account queues on that one row first, begin, batch,
//! completion and checkpoint progress for one account are serialized.
//!
//! The batch uses the bounded two-connection guard fixed by Specification
//! Amendment 2: a short guard transaction locks and validates the checkpoint
//! row, checks the batch key, and **while holding that lock** calls the
//! unchanged coordinator, which uses its own pooled connection and transaction.
//! A concurrent reclaim uses `FOR UPDATE SKIP LOCKED` on the same row, so it
//! cannot replace the token while the coordinator runs. Nothing outside the
//! local coordinator call happens inside the guard.

