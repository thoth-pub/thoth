//! ISO 3166-1 alpha-2 membership validation for the canonical ingestion
//! coordinator (`MET-WP2-01B`).
//!
//! The Metrics country dimension is a separate uppercase alpha-2
//! representation persisted as `metric_record.country_code CHAR(2)`. The
//! database enforces shape only (`^[A-Z]{2}$`); this module enforces
//! **membership**: a supplied country must be exactly one of the officially
//! assigned ISO 3166-1 alpha-2 codes, as supplied, with no automatic
//! uppercasing, trimming or aliasing. User-assigned, reserved, transitionally
//! reserved and exceptionally reserved elements (for example `XK`, `UK`, `EU`)
//! are not members.
//!
//! The list is closed inside this bounded module by design: no Cargo
//! dependency is added solely for this check, and the existing bibliographic
//! alpha-3 `CountryCode` enum is neither reused nor changed.

