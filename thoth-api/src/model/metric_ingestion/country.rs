/// Whether `code` is exactly one officially assigned ISO 3166-1 alpha-2 code.
///
/// Exact comparison: `gb`, ` GB`, `GBR` and `XK` are all rejected.
pub fn is_assigned_alpha2(code: &str) -> bool {
    ASSIGNED_ALPHA2.binary_search(&code).is_ok()
}
